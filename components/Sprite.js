export default function Sprite({ p, pokemon, size = 48 }) {
  const value = p || pokemon;
  const source = value?.species ? SPRITES[value.species] : null;
  if (!source) return <View style={[styles.fallback,{width:size,height:size}]} />;
  return <Image source={source} resizeMode="contain" style={{ width:size, height:size }} accessibilityLabel={String(value.species || value.name || 'Pokemon')} />;
}
